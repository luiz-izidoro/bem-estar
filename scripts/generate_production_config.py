#!/usr/bin/env python3
from __future__ import annotations

import argparse
import base64
import getpass
import hashlib
import os
import secrets
from pathlib import Path

ITERATIONS = 600_000


def password_hash(password: str) -> str:
    salt = secrets.token_bytes(16)
    digest = hashlib.pbkdf2_hmac("sha256", password.encode(), salt, ITERATIONS)
    salt_b64 = base64.urlsafe_b64encode(salt).decode()
    digest_b64 = base64.urlsafe_b64encode(digest).decode()
    return f"pbkdf2_sha256${ITERATIONS}${salt_b64}${digest_b64}"


def write_private(path: Path, content: str) -> None:
    path.write_text(content)
    os.chmod(path, 0o600)


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate Bem Estar production environment files and one-time access inventory"
    )
    parser.add_argument(
        "--domain", required=True, help="Public hostname, for example bemestar.example.com"
    )
    parser.add_argument("--username", default="admin")
    parser.add_argument("--output-dir", default="generated-config")
    parser.add_argument("--dashboard-password", help="Prompted securely when omitted")
    args = parser.parse_args()

    dashboard_password = args.dashboard_password or getpass.getpass("Dashboard password: ")
    if len(dashboard_password) < 12:
        raise SystemExit("Use a dashboard password with at least 12 characters.")

    out = Path(args.output_dir)
    out.mkdir(parents=True, exist_ok=True)
    os.chmod(out, 0o700)

    webhook_token = secrets.token_urlsafe(48)
    mcp_token = secrets.token_urlsafe(48)
    session_secret = secrets.token_urlsafe(64)
    grafana_password = secrets.token_urlsafe(32)
    base = f"https://{args.domain}"

    app_env = f"""# Generated by scripts/generate_production_config.py. Keep mode 0640 or stricter.
BEMESTAR_ENV=production
BEMESTAR_TIMEZONE=America/Sao_Paulo
BEMESTAR_PUBLIC_BASE_URL={base}
BEMESTAR_DATABASE_URL=sqlite:////var/lib/bem-estar/bemestar.db
BEMESTAR_RAW_DIR=/var/lib/bem-estar/raw
BEMESTAR_LOG_LEVEL=INFO
BEMESTAR_TRUSTED_HOSTS=localhost,127.0.0.1,{args.domain}
BEMESTAR_CORS_ORIGINS={base}
BEMESTAR_MAX_WEBHOOK_BYTES=26214400
BEMESTAR_RAW_RETENTION_DAYS=180
BEMESTAR_MIN_FREE_DISK_BYTES=1073741824

BEMESTAR_WEBHOOK_TOKEN={webhook_token}
BEMESTAR_MCP_TOKEN={mcp_token}
BEMESTAR_SESSION_SECRET={session_secret}
BEMESTAR_DASHBOARD_USERNAME={args.username}
BEMESTAR_DASHBOARD_PASSWORD_HASH={password_hash(dashboard_password)}

BEMESTAR_LLM_BASE_URL=
BEMESTAR_LLM_API_KEY=
BEMESTAR_LLM_MODEL=
BEMESTAR_LLM_TIMEOUT_SECONDS=30
BEMESTAR_NOTIFICATION_WEBHOOK_URL=
BEMESTAR_NOTIFICATION_WEBHOOK_TOKEN=

BEMESTAR_WORKER_POLL_SECONDS=3
BEMESTAR_RECOMPUTE_LOOKBACK_DAYS=90
BEMESTAR_WORKER_LEASE_SECONDS=900
BEMESTAR_SESSION_TTL_SECONDS=43200
BEMESTAR_LOGIN_RATE_LIMIT=5
BEMESTAR_LOGIN_RATE_WINDOW_SECONDS=60
BEMESTAR_API_RATE_LIMIT=180
BEMESTAR_API_RATE_WINDOW_SECONDS=60
BEMESTAR_WEBHOOK_RATE_LIMIT=180
BEMESTAR_WEBHOOK_RATE_WINDOW_SECONDS=60
BEMESTAR_RATE_LIMITER_MAX_KEYS=10000
"""
    obs_env = f"""GRAFANA_ROOT_URL={base}/grafana/
GRAFANA_ADMIN_USER={args.username}
GRAFANA_ADMIN_PASSWORD={grafana_password}
"""
    inventory = f"""BEM ESTAR — ONE-TIME ACCESS INVENTORY
======================================
Store these values in a password manager, then securely delete this file.

Dashboard
  URL: {base}/
  Username: {args.username}
  Password: the password you entered while running this generator

Health Auto Export webhook
  URL: {base}/webhooks/hae/v2
  Authorization header: Bearer {webhook_token}
  Stream header: X-Bemestar-Stream: <vitals|activity|sleep|workouts|reconciliation|history>

MCP
  URL: {base}/mcp
  Bearer token: {mcp_token}

Grafana
  URL: {base}/grafana/
  Username: {args.username}
  Password: {grafana_password}

Operations (not public portals)
  API health: {base}/healthz
  API readiness: {base}/readyz
  Prometheus: http://127.0.0.1:9090 (server loopback only)
  REST service: http://127.0.0.1:8787 (server loopback only)
  MCP service: http://127.0.0.1:8788 (server loopback only)
"""

    write_private(out / "bem-estar.env", app_env)
    write_private(out / "observability.env", obs_env)
    write_private(out / "ACCESS-CREDENTIALS.txt", inventory)
    print(f"Generated: {out / 'bem-estar.env'}")
    print(f"Generated: {out / 'observability.env'}")
    print(f"Generated: {out / 'ACCESS-CREDENTIALS.txt'}")
    print("Move credentials to a password manager; do not commit generated-config/.")


if __name__ == "__main__":
    main()
